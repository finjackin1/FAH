"""AutoEq project (github.com/jaakkopasanen/AutoEq, MIT) -> fonte/ui/dados/autoeq.js.
Row: [name, source, preamp, [[type, freq, q, gain], ...]]; preamp is always 0 (the UI computes it from the bands).
Get the data: git clone --filter=blob:none --no-checkout --depth 1 <repo>; git sparse-checkout set --no-cone '/results/**/*ParametricEQ.txt'; git checkout master
Usage: python -I autoeq_para_js.py <AutoEq repo folder> <commit> <out autoeq.js>"""
import json
import re
import sys
from pathlib import Path

TIPOS = {"LSC": "grave", "PK": "pico", "HSC": "agudo"}
FILTRO = re.compile(r"Filter \d+: ON (\w+) Fc ([\d.]+) Hz Gain (-?[\d.]+) dB Q ([\d.]+)")
FONTES = {"crinacle": "Crinacle", "oratory1990": "Oratory1990", "kr0mka": "Kr0mka", "freeryder05": "Freeryder05"}
LIMITE = 15.0  # dB, EQ range of the UI


def numero(texto):
    v = float(texto)
    return int(v) if v == int(v) else v


def ler(arq):
    bandas = []
    for linha in arq.read_text(encoding="utf-8").splitlines():
        m = FILTRO.match(linha.strip())
        if m:
            bandas.append([TIPOS[m[1]], numero(m[2]), float(m[4]), max(-LIMITE, min(LIMITE, float(m[3])))])
    return bandas


def main(raiz, commit, saida):
    resultados = Path(raiz) / "results"
    linhas = []
    for arq in resultados.rglob("*ParametricEQ.txt"):
        partes = arq.relative_to(resultados).parts
        bandas = ler(arq)
        if bandas:
            fonte = " ".join([FONTES.get(partes[0], partes[0]), *partes[1:-2]])
            linhas.append([partes[-2], fonte, 0.0, bandas])
    linhas.sort(key=lambda x: (x[0].casefold(), x[1]))
    corpo = json.dumps(linhas, ensure_ascii=False, separators=(",", ":"))
    Path(saida).write_text(
        f"// Generated by ferramentas/autoeq_para_js.py from AutoEq (MIT), commit {commit}. [name, source, preamp, [[type, Hz, Q, dB]]]\n"
        f"App.AUTOEQ={corpo};\n", encoding="utf-8", newline="\n")
    print(len(linhas), "fones")


if __name__ == "__main__":
    main(*sys.argv[1:4])
